"""
audit_topology_collapse_fair.py
===============================
Independent, bias-controlled audit of the "Search-Tree Topology Collapse" claim.

Bias sources in the original experiment (proposition1_precondition_intervention.py):
  B1. Only 3 hand-written Blocksworld tasks with 3 blocks (cherry-picked, tiny).
  B2. A_pred is measured on POSITIVE-ONLY transitions generated by the correct model.
      By Lemma 1 (omitting preconditions preserves all valid transitions) A_pred == 1.0
      for every omission -- a tautology, not an empirical finding.
  B3. Only the OPTIMAL planner (the most adversarial exploiter of model errors).
  B4. No control: nothing shows planner failure is worse than a non-adversarial
      (random-policy) use of the same flawed model.

This script removes those biases:
  * ALL single-precondition omissions are enumerated (no hand selection).
  * Random tasks (many seeds, several sizes) in 2 domains.
  * Two planners: optimal (A*/LM-cut) and satisficing (LAMA-first).
  * Metrics: positive-only A_pos, balanced applicability agreement A_bal,
    false-applicable rate, RANDOM-WALK failure rate (non-adversarial control),
    and planner collapse rate P(plan invalid on M* | plan found on M_hat).
  * Wilson 95% confidence intervals. No mock data; real Fast Downward runs.

Run inside WSL:  python3 src/verification/audit_topology_collapse_fair.py
"""

