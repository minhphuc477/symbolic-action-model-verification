# ----------------------------------------------------------------- utilities
def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (round(max(0, c - h), 4), round(min(1, c + h), 4))


def enumerate_omissions(domain_text: str) -> list[tuple[str, str]]:
    """Return every (action, precondition-atom-string) in the domain."""
    sexp, _ = _parse_sexp(_tokenize(domain_text))
    out = []

    def walk(node):
        if isinstance(node, list):
            if len(node) >= 2 and node[0] == ":action":
                name = node[1]
                idx = _get_section(node, ":precondition")
                prec = node[idx + 1]
                if isinstance(prec, list) and prec and prec[0] == "and":
                    for item in prec[1:]:
                        out.append((name, _sexp_to_str(item).replace("\n", " ")))
                else:
                    out.append((name, _sexp_to_str(prec).replace("\n", " ")))
            for it in node:
                walk(it)

    walk(sexp)
    return [(a, re.sub(r"\s+", " ", s).replace("( ", "(").replace(" )", ")")) for a, s in out]


def omit(domain_text: str, action: str, atom: str) -> str:
    sexp, _ = _parse_sexp(_tokenize(domain_text))
    blk = _find_action_block(sexp, action)
    idx = _get_section(blk, ":precondition")
    prec = blk[idx + 1]
    target = re.sub(r"\s+", " ", atom)
    if isinstance(prec, list) and prec and prec[0] == "and":
        keep = [prec[0]] + [
            it for it in prec[1:]
            if re.sub(r"\s+", " ", _sexp_to_str(it).replace("\n", " ")).replace("( ", "(").replace(" )", ")") != target
        ]
        blk[idx + 1] = keep
    else:
        blk[idx + 1] = ["and"]
    return _sexp_to_str(sexp) + "\n"


# ------------------------------------------------------------ task generators
def gen_blocksworld(rng: random.Random, n: int) -> tuple[str, list[str], set[str], set[str]]:
    blocks = [f"b{i}" for i in range(1, n + 1)]

    def config():
        bl = blocks[:]
        rng.shuffle(bl)
        towers, cur = [], []
        for b in bl:
            cur.append(b)
            if rng.random() < 0.45:
                towers.append(cur)
                cur = []
        if cur:
            towers.append(cur)
        return towers

    def atoms(towers, full=True):
        a = set()
        for t in towers:
            a.add(f"(ontable {t[0]})")
            for lo, hi in itertools.pairwise(t):
                a.add(f"(on {hi} {lo})")
            if full:
                a.add(f"(clear {t[-1]})")
        return a

    while True:
        it, gt = config(), config()
        init = atoms(it) | {"(handempty)"}
        goal = atoms(gt, full=False)
        if not goal <= init:
            break
    text = (
        f"(define (problem bw-{n})\n(:domain blocksworld)\n(:objects {' '.join(blocks)})\n"
        f"(:init {' '.join(sorted(init))})\n(:goal (and {' '.join(sorted(goal))}))\n)\n"
    )
    return text, blocks, init, goal


def gen_gripper(rng: random.Random, n: int) -> tuple[str, list[str], set[str], set[str]]:
    balls = [f"ball{i}" for i in range(1, n + 1)]
    room = {b: rng.choice(["rooma", "roomb"]) for b in balls}
    init = {"(at-robby rooma)", "(free left)", "(free right)"} | {f"(at {b} {room[b]})" for b in balls}
    movers = rng.sample(balls, rng.randint(2, n))
    goal = {f"(at {b} {'roomb' if room[b] == 'rooma' else 'rooma'})" for b in movers}
    text = (
        f"(define (problem gr-{n})\n(:domain gripper-strips)\n(:objects rooma roomb - room "
        f"{' '.join(balls)} - ball left right - gripper)\n(:init {' '.join(sorted(init))})\n"
        f"(:goal (and {' '.join(sorted(goal))}))\n)\n"
    )
    return text, balls, init, goal


# ------------------------------------------------------------------- planning
def run_fd(domain: Path, problem: Path, planner_args: list[str], work: Path) -> list[str] | None:
    plan = work / "plan"
    if plan.exists():
        plan.unlink()
    # --alias must precede the input files; --search goes after them.
    pre = planner_args if planner_args and planner_args[0] == "--alias" else []
    post = [] if pre else planner_args
    try:
        r = subprocess.run(
            ["python3", FD] + pre + ["--plan-file", str(plan), "--sas-file", str(work / "o.sas"),
             str(domain), str(problem)] + post,
            capture_output=True, text=True, timeout=90, cwd=str(work), check=False,
        )
    except subprocess.TimeoutExpired:
        return None
    if r.returncode != 0 or not plan.exists():
        return None
    return [ln.strip() for ln in plan.read_text().splitlines() if ln.startswith("(")]


def execute_in_gt(plan: list[str], gt_actions, init: set[str], goal: set[str]) -> bool:
    s = set(init)
    for step in plan:
        tok = step.strip("()").lower().split()
        name, args = tok[0], tok[1:]
        sch = gt_actions[name]
        pm = {p: a for p, a in zip(sch.params, args)}
        nxt = sch.apply(s, pm)
        if nxt is None:
            return False
        s = nxt
    return goal <= s


# ------------------------------------------------- balanced vs positive metrics
def ground_actions(domain_text: str, objects_typed: dict[str, str | None]):
    """Enumerate ground actions respecting :types (typed domains) or untyped."""
    res = []
    blocks = re.split(r"\(:action\s+", domain_text, flags=re.IGNORECASE)[1:]
    for blk in blocks:
        name = blk.split()[0].lower()
        m = re.search(r":parameters\s*\((.*?)\)", blk, re.DOTALL)
        toks = m.group(1).split()
        params, types, i = [], [], 0
        pend = []
        while i < len(toks):
            if toks[i] == "-":
                t = toks[i + 1]
                types += [t] * len(pend)
                pend = []
                i += 2
            else:
                params.append(toks[i])
                pend.append(toks[i])
                i += 1
        types += [None] * len(pend)
        pools = [[o for o, ot in objects_typed.items() if t is None or ot == t] for t in types]
        for combo in itertools.product(*pools):
            if len(set(combo)) == len(combo):
                res.append((name, list(combo)))
    return res


def random_states(gt_actions, init, gacts, rng, n_states=60, walk=6):
    states, s = [], set(init)
    states.append(set(s))
    for _ in range(n_states):
        app = [(a, g) for a, g in gacts if gt_actions[a].is_applicable(s, dict(zip(gt_actions[a].params, g)))]
        if not app:
            s = set(init)
            continue
        a, g = rng.choice(app)
        s = gt_actions[a].apply(s, dict(zip(gt_actions[a].params, g)))
        states.append(set(s))
    return states


def model_metrics(gt_actions, mut_actions, init, gacts, rng):
    states = random_states(gt_actions, init, gacts, rng)
    pos_ok = pos_n = 0
    agree = fa = tot = ta = 0
    for s in states:
        for a, g in gacts:
            pg = dict(zip(gt_actions[a].params, g))
            pm = dict(zip(mut_actions[a].params, g))
            gt_app = gt_actions[a].is_applicable(s, pg)
            mu_app = mut_actions[a].is_applicable(s, pm)
            tot += 1
            agree += gt_app == mu_app
            fa += (mu_app and not gt_app)
            ta += (mu_app and gt_app)
            if gt_app:  # positive-only transition set (what A_pred is built from)
                pos_n += 1
                pos_ok += gt_actions[a].apply(s, pg) == mut_actions[a].apply(s, pm)
    return {
        "A_pos_positive_only": pos_ok / pos_n if pos_n else 1.0,
        "A_bal_applicability_agreement": agree / tot,
        "false_applicable_rate": fa / tot,
        "applicability_precision": ta / (ta + fa) if (ta + fa) else 1.0,
    }


def random_walk_failure(gt_actions, mut_actions, init, gacts, rng, trials=200, length=10):
    """Non-adversarial control: random policy over M_hat-applicable actions; fail if any
    step is inapplicable in M*."""
    fails = 0
    for _ in range(trials):
        s_m, s_g, bad = set(init), set(init), False
        for _ in range(length):
            app = [(a, g) for a, g in gacts
                   if mut_actions[a].is_applicable(s_m, dict(zip(mut_actions[a].params, g)))]
            if not app:
                break
            a, g = rng.choice(app)
            pg = dict(zip(gt_actions[a].params, g))
            nxt_g = gt_actions[a].apply(s_g, pg)
            if nxt_g is None:
                bad = True
                break
            s_m = mut_actions[a].apply(s_m, dict(zip(mut_actions[a].params, g)))
            s_g = nxt_g
        fails += bad
    return fails / trials


# ----------------------------------------------------------------------- main
def audit(domain_name: str, domain_path: str, gen, sizes: list[int], tasks_per_size: int, seed: int):
    gt_text = Path(domain_path).read_text(encoding="utf-8")
    gt_actions = parse_pddl_model(gt_text)
    omissions = enumerate_omissions(gt_text)
    rng = random.Random(seed)
    rows = []
    with tempfile.TemporaryDirectory() as td:
        work = Path(td)
        gt_dom = work / "gt.pddl"
        gt_dom.write_text(gt_text)
        mut_paths = {}
        for i, (act, atom) in enumerate(omissions):
            p = work / f"mut{i}.pddl"
            p.write_text(omit(gt_text, act, atom))
            mut_paths[(act, atom)] = p
        tasks = []
        for n in sizes:
            for _ in range(tasks_per_size):
                ptxt, objs, init, goal = gen(rng, n)
                pp = work / f"prob{len(tasks)}.pddl"
                pp.write_text(ptxt)
                typed = {}
                for m in re.finditer(r"([\w\s]+?)\s-\s(\w+)", re.search(r":objects(.*?)\)\n\(:init", ptxt, re.DOTALL).group(1)):
                    for o in m.group(1).split():
                        typed[o] = m.group(2)
                if not typed:
                    typed = dict.fromkeys(objs)
                tasks.append((pp, init, goal, typed, n))
        gt_plan_cache = {}
        for (act, atom), mp in mut_paths.items():
            mut_actions = parse_pddl_model(mp.read_text())
            for ti, (pp, init, goal, typed, n) in enumerate(tasks):
                gacts = ground_actions(gt_text, typed)
                mm = model_metrics(gt_actions, mut_actions, init, gacts, random.Random(ti))
                for pname, pargs in PLANNERS.items():
                    if (ti, pname) not in gt_plan_cache:
                        gt_plan_cache[(ti, pname)] = run_fd(gt_dom, pp, pargs, work)
                    gt_plan = gt_plan_cache[(ti, pname)]
                    mu_plan = run_fd(mp, pp, pargs, work)
                    valid = None if mu_plan is None else execute_in_gt(mu_plan, gt_actions, init, goal)
                    # Length-matched non-adversarial control: a random policy over
                    # M_hat-applicable actions run for exactly as many steps as the plan.
                    rw = (random_walk_failure(gt_actions, mut_actions, init, gacts,
                                              random.Random(ti), trials=100, length=len(mu_plan))
                          if mu_plan else None)
                    rows.append({
                        "domain": domain_name, "action": act, "omitted": atom, "task": ti, "size": n,
                        "planner": pname, "gt_solvable": gt_plan is not None,
                        "mhat_plan_found": mu_plan is not None, "plan_valid_in_Mstar": valid,
                        "len_gt": len(gt_plan) if gt_plan else None,
                        "len_mhat": len(mu_plan) if mu_plan else None,
                        "random_walk_failure_len_matched": rw, **mm,
                    })
            print(f"[{domain_name}] omission {act}:{atom} done", flush=True)
    return rows


def summarize(rows):
    out = {}
    for dom in sorted({r["domain"] for r in rows}):
        for pl in PLANNERS:
            R = [r for r in rows if r["domain"] == dom and r["planner"] == pl and r["mhat_plan_found"]]
            inv = sum(1 for r in R if r["plan_valid_in_Mstar"] is False)
            allR = [r for r in rows if r["domain"] == dom and r["planner"] == pl]
            # per-omission collapse rate
            per_om = {}
            for r in R:
                per_om.setdefault((r["action"], r["omitted"]), []).append(r["plan_valid_in_Mstar"] is False)
            never = sum(1 for v in per_om.values() if not any(v))
            def mean(xs):
                xs = list(xs)
                return round(sum(xs) / len(xs), 4) if xs else None

            shortcut_rows = [r for r in R if r["len_gt"] is not None and r["len_mhat"] < r["len_gt"]]
            non_shortcut_rows = [r for r in R if r["len_gt"] is not None and r["len_mhat"] >= r["len_gt"]]
            sc_inv = sum(1 for r in shortcut_rows if r["plan_valid_in_Mstar"] is False)
            ns_inv = sum(1 for r in non_shortcut_rows if r["plan_valid_in_Mstar"] is False)

            out[f"{dom}|{pl}"] = {
                "n_plans": len(R),
                "n_unsolvable_under_Mhat": len(allR) - len(R),
                "collapse_rate_invalid_given_plan": round(inv / len(R), 4) if R else None,
                "collapse_rate_95CI": wilson(inv, len(R)),
                "omissions_that_never_collapse": f"{never}/{len(per_om)}",
                "mean_A_pos_positive_only": mean(r["A_pos_positive_only"] for r in allR),
                "mean_A_bal_applicability_agreement": mean(r["A_bal_applicability_agreement"] for r in allR),
                "mean_applicability_precision": mean(r["applicability_precision"] for r in allR),
                "mean_false_applicable_rate": mean(r["false_applicable_rate"] for r in allR),
                "planner_failure_rate": round(inv / len(R), 4) if R else None,
                "random_policy_failure_len_matched": mean(r["random_walk_failure_len_matched"] for r in R),
                "shorter_than_gt_rate": round(len(shortcut_rows) / len(R), 4) if R else None,
                "regime_I_shortcut_dc_gt_0": {
                    "n": len(shortcut_rows),
                    "planner_collapse_rate": round(sc_inv / len(shortcut_rows), 4) if shortcut_rows else None,
                    "planner_collapse_95CI": wilson(sc_inv, len(shortcut_rows)),
                    "random_policy_failure_len_matched": mean(r["random_walk_failure_len_matched"] for r in shortcut_rows),
                },
                "regime_II_cost_preserving_dc_eq_0": {
                    "n": len(non_shortcut_rows),
                    "planner_collapse_rate": round(ns_inv / len(non_shortcut_rows), 4) if non_shortcut_rows else None,
                    "planner_collapse_95CI": wilson(ns_inv, len(non_shortcut_rows)),
                    "random_policy_failure_len_matched": mean(r["random_walk_failure_len_matched"] for r in non_shortcut_rows),
                },
            }
    return out


